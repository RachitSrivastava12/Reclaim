from pathlib import Path
from playwright.sync_api import sync_playwright

BASE = 'http://127.0.0.1:3000'
OUT = Path('/private/tmp/reclaim-redesign-screenshots')
OUT.mkdir(parents=True, exist_ok=True)
results = []

def check(name, ok, detail=''):
    results.append((name, bool(ok), detail))
    print(f"{'PASS' if ok else 'FAIL'} {name} {detail}", flush=True)

def snap(page, name, width):
    page.screenshot(path=str(OUT / f'{name}-{width}.png'), full_page=True, animations='disabled')

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args=['--no-sandbox'])
    for width, height in [(1440, 900), (768, 900), (390, 844), (375, 812)]:
        context = browser.new_context(viewport={'width': width, 'height': height}, reduced_motion='reduce')
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(BASE, wait_until='networkidle')
        check(f'landing headline {width}', 'Your money. Automatically recovered.' in page.locator('h1').inner_text().replace('\n',' '))
        check(f'landing horizontal overflow {width}', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
        check(f'nav destinations {width}', page.locator('a[href="#how"]').count() >= 1 and page.locator('a[href="#proof"]').count() >= 1 and page.locator('a[href="/app"]').count() >= 1)
        snap(page, 'landing', width)
        if width <= 390:
            page.locator('.mobile-menu summary').click()
            check('mobile navigation menu', page.locator('.mobile-menu nav').is_visible() and page.locator('.mobile-menu nav a').count() == 4)
            page.locator('.mobile-menu summary').click()
        page.locator('.how-step').nth(2).click()
        check(f'how step {width}', page.locator('.how-detail h3').inner_text() == 'Validate')
        page.get_by_role('button', name='Salary matured').click()
        page.get_by_role('button', name='Run simulation').click()
        check(f'maturity simulation {width}', '300.00' in page.locator('.sim-result').inner_text())
        page.get_by_role('button', name='Replay simulation').click()
        page.get_by_role('button', name='Reset').click()
        check(f'simulation reset {width}', '0.00' in page.locator('.sim-result').inner_text())
        page.get_by_role('button', name='Salary cancelled').click()
        page.get_by_role('button', name='Run simulation').click()
        check(f'cancellation simulation {width}', '34.17' in page.locator('.sim-result').inner_text())
        snap(page, 'simulation', width)
        page.goto(BASE + '/app?walkthrough=1', wait_until='domcontentloaded')
        check(f'guided tour open {width}', page.get_by_role('dialog').is_visible())
        page.get_by_role('button', name='Show me').click()
        check(f'tour navigation {width}', 'Verified recoveries' in page.locator('h1').inner_text())
        page.keyboard.press('Escape')
        check(f'tour escape {width}', page.get_by_role('dialog').count() == 0)
        page.goto(BASE + '/app', wait_until='domcontentloaded')
        snap(page, 'dashboard', width)
        for view, expected in [('streams','Inspect a stream'),('policies','Recovery policies'),('executions','Verified recoveries'),('status','Network status')]:
            page.locator(f'.sidebar button:has-text("{dict(streams="Streams",policies="Policies",executions="Verified recoveries",status="Network status")[view]}")').click()
            check(f'{view} navigation {width}', expected in page.locator('h1').inner_text())
            check(f'{view} overflow {width}', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
            if view in ('streams','policies','status'):
                page.locator('.read-time, .notice[role=alert]').first.wait_for(timeout=25000)
            snap(page, view, width)
        page.goto(BASE + '/app?view=executions&case=cancellation', wait_until='domcontentloaded')
        page.locator('.explorer-switch button').nth(1).click()
        check(f'execution switch {width}', 'Maturity recovery' in page.locator('.execution-head').inner_text() and 'case=maturity' in page.url)
        check(f'receipts {width}', page.locator('.execution-step a[href*="/tx/0x"]').count() == 7)
        page.locator('.step-evidence details summary').first.click()
        check(f'technical detail {width}', page.locator('.step-evidence details').first.evaluate('(el) => el.open'))
        snap(page, 'maturity-trace', width)
        page.goto(BASE + '/app?view=streams', wait_until='domcontentloaded')
        page.locator('#stream-id').fill('abc')
        page.get_by_role('button', name='Inspect').click()
        check(f'input error {width}', page.locator('.field-error').is_visible())
        page.get_by_role('button', name='213', exact=True).click()
        check(f'stream preset {width}', page.locator('#stream-id').input_value() == '213')
        page.goto(BASE + '/app?view=policies', wait_until='domcontentloaded')
        check(f'policy write controls removed {width}', page.get_by_role('button', name='Connect wallet').count() == 0 and page.get_by_role('button', name='Enroll / replace').count() == 0)
        check(f'retirement disclosure {width}', 'permanently retired' in page.locator('.policy-info').inner_text())
        check(f'javascript errors {width}', not errors, '; '.join(errors))
        context.close()
    context = browser.new_context(viewport={'width':1440,'height':900}, permissions=['clipboard-read','clipboard-write'])
    page = context.new_page()
    page.goto(BASE + '/app?view=executions', wait_until='domcontentloaded')
    page.locator('.step-evidence .copy-button').first.click()
    copied = page.evaluate('navigator.clipboard.readText()')
    check('copy receipt hash', copied.startswith('0x') and len(copied) == 66)
    page.goto(BASE, wait_until='domcontentloaded')
    check('landing links have destinations', page.locator('a:not([href]), a[href=""], a[href="#"]').count() == 0)
    page.goto(BASE + '/app', wait_until='domcontentloaded')
    page.get_by_role('button', name='Explore verified recovery').click()
    check('overview proof CTA', 'Verified recoveries' in page.locator('h1').inner_text())
    page.goto(BASE + '/app', wait_until='domcontentloaded')
    page.get_by_role('button', name='Protocol status').click()
    check('overview status CTA', 'Network status' in page.locator('h1').inner_text())
    page.goto(BASE + '/app?view=streams', wait_until='domcontentloaded')
    page.get_by_role('button', name='213', exact=True).click()
    page.get_by_role('button', name='214', exact=True).click()
    check('214 preset', page.locator('#stream-id').input_value() == '214')
    page.locator('.stream-panel .icon-button').wait_for(timeout=25000)
    page.locator('.stream-panel .icon-button').click()
    check('refresh stream action', page.locator('.stream-panel, .notice[role=alert]').count() > 0)
    page.goto(BASE + '/app?view=status', wait_until='domcontentloaded')
    page.get_by_role('button', name='Refresh live read').wait_for(timeout=25000)
    page.get_by_role('button', name='Refresh live read').click()
    check('refresh network action', page.locator('.read-time, .notice[role=alert]').count() > 0)
    page.route('**/api/status', lambda route: route.abort())
    page.goto(BASE + '/app?view=status', wait_until='domcontentloaded')
    page.locator('.notice[role=alert]').wait_for(timeout=25000)
    check('RPC error recovery', page.get_by_role('button', name='Retry read').is_visible() and page.locator('a[href="/app?view=executions"]').count() > 0)
    page.get_by_role('button', name='Retry read').click()
    page.locator('.notice[role=alert]').wait_for(timeout=25000)
    check('RPC retry action', page.locator('.notice[role=alert]').count() > 0)
    snap(page, 'rpc-error', 1440)
    page.route('**/api/stream/*', lambda route: route.abort())
    page.goto(BASE + '/app?view=streams', wait_until='domcontentloaded')
    page.locator('.notice[role=alert]').wait_for(timeout=25000)
    check('stream RPC error recovery', page.get_by_role('button', name='Retry read').is_visible() and page.locator('a[href="/app?view=executions"]').count() > 0)
    snap(page, 'stream-rpc-error', 1440)
    context.close()
    context = browser.new_context(viewport={'width':1440,'height':900}, reduced_motion='no-preference')
    page = context.new_page()
    page.goto(BASE, wait_until='domcontentloaded')
    page.get_by_role('button', name='Run simulation').click()
    page.locator('.sim-stage.done').first.wait_for(timeout=2000)
    page.locator('.sim-stage.done').nth(3).wait_for(timeout=6000)
    check('animated stages complete', '34.17' in page.locator('.sim-result').inner_text())
    context.close()
    browser.close()

print(f'RESULT: {sum(ok for _,ok,_ in results)}/{len(results)} checks passed; screenshots: {OUT}')
if not all(ok for _,ok,_ in results): raise SystemExit(1)
